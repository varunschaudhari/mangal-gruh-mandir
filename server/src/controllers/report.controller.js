export const getLowStockWhatsApp = asyncHandler(async (req, res) => {
  const { department } = req.query;
  const balances = await getLowStockData(department);

  const outOfStock = balances.filter((b) => b.alertLevel === 'out_of_stock');
  const lowStock   = balances.filter((b) => b.alertLevel === 'low_stock');
  const reorder    = balances.filter((b) => b.alertLevel === 'reorder');

  const lines = [
    `*🕉️ Mangal Grah Mandir, Amalner*`,
    `*Stock Alert Report – ${new Date().toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' })}*`,
    '',
  ];

  if (outOfStock.length) {
    lines.push(`❌ *Out of Stock (${outOfStock.length}):*`);
    outOfStock.forEach((b) => {
      lines.push(`  • ${b.product?.name} (${b.department?.name}) – 0 ${b.product?.unit?.symbol || ''}`);
    });
    lines.push('');
  }

  if (lowStock.length) {
    lines.push(`⚠️ *Low Stock (${lowStock.length}):*`);
    lowStock.forEach((b) => {
      lines.push(`  • ${b.product?.name} (${b.department?.name}) – ${b.quantity}/${b.product?.minStockLevel || '?'} ${b.product?.unit?.symbol || ''}`);
    });
    lines.push('');
  }

  if (reorder.length) {
    lines.push(`📦 *Reorder Soon (${reorder.length}):*`);
    reorder.forEach((b) => {
      lines.push(`  • ${b.product?.name} (${b.department?.name}) – ${b.quantity} ${b.product?.unit?.symbol || ''}`);
    });
    lines.push('');
  }

  if (!balances.length) lines.push('✅ All products are adequately stocked.');

  lines.push(`_Generated by MGM Stock System_`);
  res.json(new ApiResponse(200, { text: lines.join('\n') }));
});

