export const getDailyReport = asyncHandler(async (req, res) => {
  const { date, departmentId } = await resolveParams(req.query);
  const { transactions, summary } = await getDailyReportData(date, departmentId);
  res.json(new ApiResponse(200, { date, transactions, summary }));
});

