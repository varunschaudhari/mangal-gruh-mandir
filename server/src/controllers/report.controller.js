function today() { return new Date().toISOString().split('T')[0]; }

async function resolveParams(query) {
  const { date, department: departmentId } = query;
  if (!date) throw new ApiError(400, 'date is required (YYYY-MM-DD)');
  let departmentName = null;
  if (departmentId) {
    const dept = await Department.findById(departmentId).lean();
    departmentName = dept?.name || null;
  }
  return { date, departmentId, departmentName };
}

