export const getExpiringWhatsApp = asyncHandler(async (req, res) => {
  const { days = 30, department } = req.query;
  const batches = await getExpiringBatchData(Number(days), department);

  const now = new Date();
  const expired  = batches.filter((b) => new Date(b.expiryDate) < now);
  const expiring = batches.filter((b) => new Date(b.expiryDate) >= now);

  const fmt = (d) => new Date(d).toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' });

  const lines = [
    `*🕉️ Mangal Grah Mandir, Amalner*`,
    `*Expiring Stock – Within ${days} Days*`,
    '',
  ];

  if (expired.length) {
    lines.push(`🔴 *Already Expired (${expired.length}):*`);
    expired.forEach((b) => {
      const d = Math.abs(Math.ceil((new Date(b.expiryDate) - now) / 86400000));
      lines.push(`  • ${b.product?.name} (${b.department?.name}) – ${b.remainingQty} ${b.product?.unit?.symbol || ''} – expired ${d}d ago (${fmt(b.expiryDate)})`);
    });
    lines.push('');
  }

  if (expiring.length) {
    lines.push(`🟡 *Expiring Soon (${expiring.length}):*`);
    expiring.forEach((b) => {
      const d = Math.ceil((new Date(b.expiryDate) - now) / 86400000);
      lines.push(`  • ${b.product?.name} (${b.department?.name}) – ${b.remainingQty} ${b.product?.unit?.symbol || ''} – ${d} day${d !== 1 ? 's' : ''} left (${fmt(b.expiryDate)})`);
    });
    lines.push('');
  }

  if (!batches.length) lines.push(`✅ No batches expiring within ${days} days.`);

  lines.push(`_Generated by MGM Stock System_`);
  res.json(new ApiResponse(200, { text: lines.join('\n') }));
});

