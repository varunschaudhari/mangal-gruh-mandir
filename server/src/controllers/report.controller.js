export const getDailyWhatsApp = asyncHandler(async (req, res) => {
  const { date, departmentId, departmentName } = await resolveParams(req.query);
  const { transactions, summary } = await getDailyReportData(date, departmentId);

  const dateLabel = new Date(date).toLocaleDateString('en-IN', { day: '2-digit', month: 'short', year: 'numeric' });

  const lines = [
    `*🕉️ Mangal Grah Mandir, Amalner*`,
    `*Daily Stock Report – ${dateLabel}*`,
    departmentName ? `Department: ${departmentName}` : '',
    '',
    `📦 *Stock In:* ${summary.STOCK_IN.count} entries (${summary.STOCK_IN.totalQty} units)`,
    `📤 *Stock Out:* ${summary.STOCK_OUT.count} entries (${summary.STOCK_OUT.totalQty} units)`,
    `↔️ *Transfers:* ${summary.TRANSFER.count} entries`,
    `🗑️ *Wastage:* ${summary.WASTAGE.count} entries (${summary.WASTAGE.totalQty} units)`,
  ].filter((l) => l !== undefined);

  // Stock In details
  const stockIn = transactions.filter((t) => t.transactionType === 'STOCK_IN');
  if (stockIn.length) {
    lines.push('', '*Stock In:*');
    stockIn.forEach((t) => {
      const ref = t.supplier?.name ? ` (${t.supplier.name})` : t.donorName ? ` (Donor: ${t.donorName})` : '';
      lines.push(`  • ${t.product?.name}: +${t.quantity} ${t.unit?.symbol || ''}${ref} → ${t.toDepartment?.name}`);
    });
  }

  // Stock Out details
  const stockOut = transactions.filter((t) => t.transactionType === 'STOCK_OUT');
  if (stockOut.length) {
    lines.push('', '*Stock Out:*');
    stockOut.forEach((t) => {
      lines.push(`  • ${t.product?.name}: -${t.quantity} ${t.unit?.symbol || ''} from ${t.fromDepartment?.name}`);
    });
  }

  // Wastage details
  const wastage = transactions.filter((t) => t.transactionType === 'WASTAGE');
  if (wastage.length) {
    lines.push('', '*Wastage:*');
    wastage.forEach((t) => {
      lines.push(`  • ${t.product?.name}: ${t.quantity} ${t.unit?.symbol || ''} (${t.wastageReason || ''}) from ${t.fromDepartment?.name}`);
    });
  }

  // Transfer details
  const transfers = transactions.filter((t) => t.transactionType === 'TRANSFER');
  if (transfers.length) {
    lines.push('', '*Transfers:*');
    transfers.forEach((t) => {
      lines.push(`  • ${t.product?.name}: ${t.quantity} ${t.unit?.symbol || ''} ${t.fromDepartment?.name} → ${t.toDepartment?.name}`);
    });
  }

  lines.push('', `_Generated by MGM Stock System_`);

  res.json(new ApiResponse(200, { text: lines.join('\n') }));
});
